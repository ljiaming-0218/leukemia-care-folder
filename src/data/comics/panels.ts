const byChapter = new Map<string, ComicPanel[]>();
for (const panel of comicPanels) {
  const list = byChapter.get(panel.chapterId) ?? [];
  list.push(panel);
  byChapter.set(panel.chapterId, list);
}
for (const list of byChapter.values()) list.sort((a, b) => a.order - b.order);

export function getComicPanels(chapterId: string): ComicPanel[] {
  return byChapter.get(chapterId) ?? [];
}
